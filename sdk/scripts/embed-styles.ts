/// <reference types="bun" />
import { readFile, watch, writeFile } from "node:fs/promises"
import process from "node:process"
import { createThemeCss, themeTokenClasses } from "@tanstack/highlight/theme"
import { githubDarkTheme } from "@tanstack/highlight/themes/github-dark"
import { githubLightTheme } from "@tanstack/highlight/themes/github-light"
// Wraps the Tailwind CLI output into a TypeScript module, because the chat widget must carry its
// compiled stylesheet as a string to inject into its own shadow root.
const header = "// Generated by `bun run generate:styles` from src/styles.css. Do not edit.\n"
let embedded = ""
const highlightCss =
  createThemeCss({
    light: githubLightTheme,
    dark: githubDarkTheme,
    lightSelector: ".astralbeam-root",
    darkSelector: ".astralbeam-root.dark",
    includeBaseStyles: false,
  }) + themeTokenClasses.map((token) => `.th-${token}{color:var(--th-${token})}`).join("")

async function embedStyles(): Promise<void> {
  let css = await readFile(".generated/styles.css", "utf8")
  css += highlightCss

  // Unwrap the @supports gate around Tailwind's default custom properties (`@layer properties`):
  // browsers ignore @property inside shadow trees, so the fallback must apply everywhere.
  const gate = "@layer properties{@supports "
  const gateStart = css.indexOf(gate)
  if (gateStart !== -1) {
    const open = css.indexOf("{", gateStart + gate.length)
    let depth = 1
    let close = open + 1
    while (close < css.length && depth > 0) {
      if (css[close] === "{") depth++
      else if (css[close] === "}") depth--
      close++
    }
    // `close - 1` closes the @supports block; the brace after it closes the @layer block.
    const defaults = css.slice(open + 1, close - 1)
    css = css.slice(0, gateStart) + "@layer properties{" + defaults + "}" + css.slice(close + 1)
  }
  // An unchanged rewrite would still trigger a `tsdown --watch` rebuild.
  if (css === embedded) return
  embedded = css
  await writeFile(
    "src/widget/styles.generated.ts",
    `${header}export const chatStyles: string = ${JSON.stringify(css)}\n`,
  )
}

await embedStyles()
// `bun run dev` pairs `--watch` with `tailwindcss --watch`, so new classes reach the bundle.
if (process.argv.slice(2).includes("--watch")) {
  for await (const _event of watch(".generated")) await embedStyles()
}
