import { captureMilestone } from "@e2e/capture.ts"
import { expectToast } from "@e2e/dialogs.ts"
import { expect, test } from "@e2e/fixtures.ts"
import { operatorKey } from "@e2e/worktree.ts"

test("configure sections preserve unsaved settings and saved summaries when collapsed", async ({
  page,
  configure,
}) => {
  test.setTimeout(90_000)
  await configure.open()
  await configure.signIn(operatorKey)
  const storage = configure.section("File storage")
  const storageTrigger = storage.getByRole("button", { name: "File storage", exact: true })
  const general = configure.section("General")
  const generalTrigger = general.getByRole("button", { name: "General", exact: true })
  const authentication = configure.section("Authentication")
  const savedToast = page.locator('[data-slot="toast"]').filter({
    has: page.getByText("Configuration saved", { exact: true }),
  })
  const completeBanner = page.getByText("Configuration is complete", { exact: true })
  const saveButton = page.getByRole("button", { name: "Save", exact: true }).first()
  const originalSupportEmail = await configure.field("support_email_address").inputValue()
  const draftSupportEmail = `draft-support-${Date.now()}@example.com`
  await expect(storageTrigger).toHaveAttribute("aria-expanded", "false")
  await expect(storage.getByText("Configured", { exact: true })).toBeVisible()
  await expect(configure.field("s3_bucket")).toBeHidden()
  await expect(authentication.getByText("Configured", { exact: true })).toBeVisible()
  await expect(savedToast).toBeHidden()
  await expect(completeBanner).toHaveCount(0)
  expect((await storageTrigger.boundingBox())!.height).toBeGreaterThanOrEqual(44)
  await captureMilestone(page, "configure-collapsed-summary")

  await configure.setValue("support_email_address", draftSupportEmail)
  await expect(savedToast).toBeHidden()
  await configure.setValue("support_email_address", originalSupportEmail)
  await expect(savedToast).toBeHidden()
  await configure.setValue("support_email_address", draftSupportEmail)
  await expect(savedToast).toBeHidden()
  await expect(general.getByText("Unsaved changes", { exact: true })).toBeVisible()
  await generalTrigger.click()
  await expect(configure.field("support_email_address")).toBeHidden()
  await expect(generalTrigger).toContainText(originalSupportEmail)
  await expect(generalTrigger).not.toContainText(draftSupportEmail)
  await captureMilestone(page, "configure-unsaved-status")
  await generalTrigger.focus()
  await page.keyboard.press("Enter")
  await expect(configure.field("support_email_address")).toHaveValue(draftSupportEmail)
  await configure
    .fieldGroup("support_email_address")
    .getByRole("button", { name: "Discard" })
    .click()
  await expect(savedToast).toBeHidden()

  await configure.setValue("s3_secret_access_key", "unsaved-storage-secret")
  await expect(savedToast).toBeHidden()
  await expect(generalTrigger).toHaveAttribute("aria-expanded", "true")
  await storageTrigger.click()
  await expect(storage.getByText("Unsaved changes", { exact: true })).toBeVisible()
  await expect(storageTrigger).not.toContainText("unsaved-storage-secret")
  await storageTrigger.click()
  await expect(configure.field("s3_secret_access_key")).toHaveValue("unsaved-storage-secret")
  await configure
    .fieldGroup("s3_secret_access_key")
    .getByRole("button", { name: "Discard" })
    .click()
  await expect(savedToast).toBeHidden()
  await storageTrigger.click()
  await generalTrigger.click()

  await configure.setValue("support_email_address", "invalid-email")
  await generalTrigger.click()
  await saveButton.click()
  await expectToast(page, "Some values could not be saved")
  await expect(generalTrigger).toHaveAttribute("aria-expanded", "true")
  await expect(configure.fieldGroup("support_email_address").getByRole("alert")).toBeVisible()
  await expect(savedToast).toBeHidden()
  await captureMilestone(page, "configure-failed-save-status")
  await generalTrigger.click()
  await saveButton.click()
  await expectToast(page, "Some values could not be saved")
  await expect(generalTrigger).toHaveAttribute("aria-expanded", "true")
  await configure
    .fieldGroup("support_email_address")
    .getByRole("button", { name: "Discard" })
    .click()
  await expect(
    configure.fieldGroup("support_email_address").locator('[data-slot="field-error"]'),
  ).toHaveCount(0)
  await expect(general.getByText("Configured", { exact: true })).toBeVisible()
  await expect(saveButton).toBeDisabled()
  await expect(savedToast).toBeHidden()
  await captureMilestone(page, "configure-validation-restored")
  await configure.setValue("support_email_address", draftSupportEmail)
  await expect(savedToast).toBeHidden()
  await generalTrigger.click()
  try {
    await saveButton.click()
    await expect(generalTrigger).toContainText(draftSupportEmail)
    await expect(general.getByText("Configured", { exact: true })).toBeVisible()
    await expect(savedToast).toBeVisible()
    await expect(completeBanner).toHaveCount(0)
    await captureMilestone(page, "configure-saved-toast")
    await configure.setValue("support_email_address", originalSupportEmail)
    await expect(savedToast).toHaveCount(0, { timeout: 2_500 })
    await configure.setValue("support_email_address", draftSupportEmail)
    await expect(savedToast).toBeHidden()
    await configure.setValue("support_email_address", originalSupportEmail)
    await configure
      .fieldGroup("support_email_address")
      .getByRole("button", { name: "Discard" })
      .click()
    await expect(savedToast).toBeHidden()
    await generalTrigger.click()
    await captureMilestone(page, "configure-edit-cleared-toast")
    await page.reload()
    await expect(configure.field("support_email_address")).toHaveValue(draftSupportEmail)
    await expect(savedToast).toBeHidden()
    await configure.setValue("support_email_address", originalSupportEmail)
    await generalTrigger.click()
    await saveButton.click()
    await expect(savedToast).toBeVisible()
    await expect(completeBanner).toHaveCount(0)
    await captureMilestone(page, "configure-restored-success-toast")
    await page.mouse.move(0, 0)
    await expect(savedToast).toHaveCount(0, { timeout: 8_000 })
    await captureMilestone(page, "configure-toast-dismissed")
    await page.reload()
    await expect(savedToast).toBeHidden()
  } finally {
    await page.reload()
    if ((await configure.field("support_email_address").inputValue()) !== originalSupportEmail) {
      await configure.setValue("support_email_address", originalSupportEmail)
      await generalTrigger.click()
      await configure.save()
    }
    await page.reload()
  }
  await expect(generalTrigger).toContainText(originalSupportEmail)
  await expect(savedToast).toBeHidden()
  await expect(completeBanner).toHaveCount(0)

  await expect(page.getByRole("button", { name: "Save", exact: true }).first()).toBeDisabled()
  await captureMilestone(page, "configure-sections-restored")

  await page.setViewportSize({ width: 390, height: 844 })
  await expect(storageTrigger).toHaveAttribute("aria-expanded", "false")
  await captureMilestone(page, "configure-mobile-summary")
  expect((await storageTrigger.boundingBox())!.height).toBeGreaterThanOrEqual(44)
  await storageTrigger.click()
  await expect(configure.field("s3_bucket")).toBeVisible()
  await captureMilestone(page, "configure-mobile-expanded")
})
