const BOOTSTRAP_ENVIRONMENT_FILE = join(homedir(), ".astralbeam", "platform.json")

const BOOTSTRAP_PROMPTS = {
  DATABASE_URL: "PostgreSQL connection URL (DATABASE_URL):",
  DATABASE_ENCRYPTION_KEY:
    "Encryption keyring, 32+ characters per entry (DATABASE_ENCRYPTION_KEY):",
}

// Release asset suffixes keyed by `${process.platform}-${process.arch}`.
const RELEASE_TARGETS: Record<string, string> = {
  "linux-x64": "linux-x86_64",
  "linux-arm64": "linux-arm64",
  "darwin-x64": "macos-x86_64",
  "darwin-arm64": "macos-arm64",
  "win32-x64": "windows-x86_64.exe",
}

const BINARY_HOST = `${process.platform}-${process.arch}`
const RELEASE_TARGET = RELEASE_TARGETS[BINARY_HOST]
const VERSION_OUTPUT = `${APP_HANDLE}-platform ${packageJson.version} (${RELEASE_TARGET ?? BINARY_HOST})`

type BootstrapVariable = keyof typeof BOOTSTRAP_PROMPTS
type BootstrapOptions = {
  microsandbox?: boolean
  embeddedpg?: boolean
  standalone?: boolean
}

// Fills unset variables from the saved file, prompts on a terminal for any still missing, and
// reports where each value came from.
function loadBootstrapEnvironment(names: BootstrapVariable[], { promptMissing = true } = {}): void {
  const unset = names.filter((name) => process.env[name] === undefined)
  const saved = (
    unset.length && existsSync(BOOTSTRAP_ENVIRONMENT_FILE)
      ? JSON.parse(readFileSync(BOOTSTRAP_ENVIRONMENT_FILE, "utf8"))
      : {}
  ) as Partial<Record<BootstrapVariable, string>>
  const missing = promptMissing ? unset.filter((name) => !saved[name]) : []
  for (const name of missing) {
    const value = prompt(BOOTSTRAP_PROMPTS[name])?.trim()
    if (value) saved[name] = value
  }
  if (missing.some((name) => saved[name])) {
    mkdirSync(dirname(BOOTSTRAP_ENVIRONMENT_FILE), { recursive: true, mode: 0o700 })
    writeFileSync(BOOTSTRAP_ENVIRONMENT_FILE, `${JSON.stringify(saved, null, 2)}\n`, {
      mode: 0o600,
    })
    console.error(`Saved to ${BOOTSTRAP_ENVIRONMENT_FILE}`)
  }
  for (const name of names) {
    if (process.env[name] !== undefined) {
      console.error(`Using ${name} from the environment`)
    } else if (saved[name]) {
      process.env[name] = saved[name]
      console.error(`Using ${name} from ${BOOTSTRAP_ENVIRONMENT_FILE}`)
    }
  }
}

function saveBootstrapValue({ name, value }: { name: string; value: string }): void {
  const path = join(process.cwd(), ".env")
  if (existsSync(path)) chmodSync(path, 0o600)
  writeFileSync(path, `\n${name}=${value}\n`, { flag: "a", mode: 0o600 })
  console.error(`Saved ${name} to ${path}`)
}

async function preparePlatformDatabase(options: { embeddedpg?: boolean } = {}): Promise<boolean> {
  loadBootstrapEnvironment(["DATABASE_URL", "DATABASE_ENCRYPTION_KEY"], { promptMissing: false })
  if (options.embeddedpg) process.env.DATABASE_URL ??= "embedded"
  if (process.env.DATABASE_URL !== "embedded") {
    getDatabaseUrl()
    return false
  }
  if (process.env.DATABASE_ENCRYPTION_KEY !== undefined) getDatabaseEncryptionKeyring()
  await startEmbeddedPostgres({ directory: getDataDirectory() })
  return true
}

async function preparePlatformMicrosandbox(): Promise<boolean> {
  try {
    const { checkMicrosandboxRuntime } = await import("@scripts/microsandbox-runtime.ts")
    const sdkPath = await checkMicrosandboxRuntime({
      directory: getDataDirectory(),
    })
    if (!sdkPath) return false
    process.env.__ASTRALBEAM_INTERNAL_MICROSANDBOX_SDK = sdkPath
    return true
  } catch (error) {
    console.error(
      `Microsandbox unavailable: ${error instanceof Error ? error.message : String(error)}`,
    )
    return false
  }
}

async function validatePlatformMicrosandboxInChild(): Promise<void> {
  // Until Bun propagates process.env to native addons, validate with the prepared OS environment.
  // https://github.com/superradcompany/microsandbox/blob/v0.7.13/sdk/rust/lib/config/mod.rs
  const entry = Bun.isStandaloneExecutable ? [] : [fileURLToPath(import.meta.url)]
  const child = spawn(process.execPath, [...entry, "_validate-microsandbox"], {
    env: process.env,
    stdio: ["ignore", "inherit", "inherit", "ipc"],
  })
  const code = await new Promise<number | null>((resolve, reject) => {
    child.once("error", reject)
    child.once("exit", resolve)
  })
  if (code !== 0) throw new Error("Microsandbox validation process failed")
}

async function validatePlatformMicrosandbox(): Promise<void> {
  const sdkPath = process.env.__ASTRALBEAM_INTERNAL_MICROSANDBOX_SDK
  if (!sdkPath) throw new Error("Microsandbox runtime is not prepared")
  const controller = new AbortController()
  const stop = () => controller.abort()
  const signals = ["SIGINT", "SIGTERM", "disconnect"] as const
  for (const signal of signals) process.once(signal, stop)
  try {
    if (!process.connected) throw new Error("Microsandbox validation requires a bootstrap parent")
    const { Microsandbox } = await import("@astralbeam/sandbox")
    await new Microsandbox({ image: getLocalSandboxImage(), sdkPath }).valid({
      signal: controller.signal,
    })
  } finally {
    for (const signal of signals) process.off(signal, stop)
    if (process.connected) process.disconnect?.()
  }
}

async function preparePlatformSandboxes({ prepareImages = false } = {}): Promise<void> {
  if (process.env.__ASTRALBEAM_INTERNAL_WORKER_ID !== undefined) return
  delete process.env.__ASTRALBEAM_INTERNAL_MICROSANDBOX_SDK
  const { DockerSandbox, SandboxConnection } = await import("@astralbeam/sandbox")
  // External providers inherit this check without initializing their SDKs or credentials.
  const checks = [
    ["Daytona", SandboxConnection.available()],
    [
      "Docker",
      process.env.DOCKERSANDBOX_DISABLED === "true"
        ? Promise.resolve("disabled")
        : DockerSandbox.available(),
    ],
    ["E2B", SandboxConnection.available()],
    [
      "Microsandbox",
      process.env.MICROSANDBOX_DISABLED === "true"
        ? Promise.resolve("disabled")
        : preparePlatformMicrosandbox(),
    ],
    ["Sprites", SandboxConnection.available()],
    ["Vercel", SandboxConnection.available()],
  ] as const
  const checked = await Promise.allSettled(
    checks.map(async ([name, checking]) => {
      const result = await checking
      const required =
        (name === "Docker" && process.env.DOCKERSANDBOX_DISABLED === "false") ||
        (name === "Microsandbox" && process.env.MICROSANDBOX_DISABLED === "false")
      if (required && !result) throw new Error(`${name} is required but is unavailable`)
      if (
        prepareImages &&
        result !== "disabled" &&
        (name === "Docker" || name === "Microsandbox")
      ) {
        const image = getLocalSandboxImage()
        if (name === "Docker") {
          if (result)
            await runBootstrapStep({
              name: `Docker image ${image}`,
              run: () => DockerSandbox.prepareImage(image),
            })
        } else {
          const { pullMicrosandboxImage } = await import("@scripts/microsandbox-runtime.ts")
          await pullMicrosandboxImage({ directory: getDataDirectory(), image })
        }
        if (required) {
          try {
            if (name === "Docker") await new DockerSandbox({ image }).valid()
            else await validatePlatformMicrosandboxInChild()
          } catch (cause) {
            throw new Error(`${name} is required but its connection test failed`, { cause })
          }
        }
      }
      const status = result === "disabled" ? "disabled" : result ? "available" : "unavailable"
      console.error(`Sandbox ${name}: ${status}`)
    }),
  )
  for (const result of checked) if (result.status === "rejected") throw result.reason
}

async function runBootstrapStep<A>(options: { name: string; run: () => Promise<A> }): Promise<A> {
  const started = performance.now()
  console.error(`${options.name}: starting`)
  try {
    const result = await options.run()
    console.error(
      `${options.name}: complete (${((performance.now() - started) / 1000).toFixed(1)}s)`,
    )
    return result
  } catch (error) {
    console.error(`${options.name}: failed`)
    throw error
  }
}

async function migratePlatformDatabase(dryRun: boolean): Promise<void> {
  try {
    const names = await migrateDatabase({ dryRun })
    if (names.length === 0) return console.log("No pending migrations")
    console.log(
      `${dryRun ? "Pending" : "Applied"} ${names.length} migration${names.length === 1 ? "" : "s"}:`,
    )
    for (const name of names) console.log(`  ${name}`)
  } finally {
    await stopEmbeddedPostgres()
  }
}

const program = new Command(`${APP_HANDLE}-platform`)
  .description("Run the platform server and its maintenance commands.")
  .version(VERSION_OUTPUT)
  .addHelpText("after", CLI_HELP_FOOTER)

program.command("_validate-microsandbox", { hidden: true }).action(validatePlatformMicrosandbox)

program
  .command("start", { isDefault: true })
  .description("start the server (the default command)")
  .action(async () => {
    const prepared = await Promise.allSettled([
      preparePlatformSandboxes(),
      preparePlatformDatabase(),
    ])
    for (const result of prepared) if (result.status === "rejected") throw result.reason
    loadBootstrapEnvironment(["DATABASE_ENCRYPTION_KEY"])
    getDatabaseEncryptionKeyring()
    process.env.PORT ||= "4510"
    const { startPlatformServer } = await import("../server.ts")
    await startPlatformServer()
  })

program
  .command("bootstrap")
  .description("initialize missing environment defaults and apply pending migrations")
  .option("--microsandbox", "prepare the local Microsandbox SDK and runtime")
  .option("--embeddedpg", "prepare private persistent PostgreSQL")
  .addOption(
    new Option("--standalone", "prepare local file storage, PostgreSQL, and Microsandbox").implies({
      embeddedpg: true,
      microsandbox: true,
    }),
  )
  .action(async (options: BootstrapOptions) => {
    const started = performance.now()
    const directory = getDataDirectory()
    console.error(`Bootstrapping ${program.name()} using data directory ${directory}`)
    const installed = await Promise.allSettled([
      options.microsandbox
        ? runBootstrapStep({
            name: "Microsandbox runtime",
            run: async () => {
              const { installMicrosandboxRuntime } =
                await import("@scripts/microsandbox-runtime.ts")
              await installMicrosandboxRuntime({ directory })
            },
          })
        : undefined,
      options.embeddedpg
        ? runBootstrapStep({
            name: "PostgreSQL runtime",
            run: () => installEmbeddedPostgres({ directory }),
          })
        : undefined,
    ])
    for (const result of installed) if (result.status === "rejected") throw result.reason
    const databaseWasConfigured = process.env.DATABASE_URL !== undefined
    const embedded = await runBootstrapStep({
      name: "Database startup",
      run: () => preparePlatformDatabase(options),
    })
    if (process.env.DATABASE_ENCRYPTION_KEY !== undefined) getDatabaseEncryptionKeyring()
    const storedKeys = new Set<string>()
    const client = new Client({
      connectionString: getDatabaseUrl(),
      connectionTimeoutMillis: 5_000,
    })
    try {
      await client.connect()
      const { rows } = await client.query<{ present: boolean }>(
        "SELECT to_regclass('config') IS NOT NULL AS present",
      )
      if (rows[0]?.present) {
        const stored = await client.query<{ key: string }>("SELECT key FROM config")
        for (const row of stored.rows) storedKeys.add(row.key.toUpperCase())
      }
    } finally {
      await client.end()
    }
    // Existing deployments must keep their encryption key and secure flag defaults.
    if (storedKeys.size > 0) getDatabaseEncryptionKeyring()
    const testingDefault = storedKeys.size === 0 ? "true" : "false"
    const defaults = {
      ...(options.standalone && {
        ...(storedKeys.size === 0 && { STORAGE_PROVIDER: "filesystem" }),
        MICROSANDBOX_DISABLED: "false",
      }),
      LOCAL_SANDBOX_IMAGE: getLocalSandboxImage(),
      DATABASE_ENCRYPTION_KEY: randomBytes(32).toString("base64url"),
      BETTER_AUTH_SECRET: randomBytes(32).toString("base64url"),
      ALLOW_INSECURE: testingDefault,
      SKIP_EMAIL_VERIFICATION: testingDefault,
      TURNSTILE_SITE_KEY: "1x00000000000000000000AA",
      TURNSTILE_SECRET_KEY: "1x0000000000000000000000000000000AA",
    }
    for (const [name, value] of Object.entries(defaults)) {
      if (process.env[name] !== undefined || storedKeys.has(name)) continue
      saveBootstrapValue({ name, value })
      process.env[name] = value
    }
    getDatabaseEncryptionKeyring()
    const [migration, sandboxes] = await Promise.allSettled([
      runBootstrapStep({ name: "Database migrations", run: () => migratePlatformDatabase(false) }),
      runBootstrapStep({
        name: "Local sandbox images and validation",
        run: () => preparePlatformSandboxes({ prepareImages: true }),
      }),
    ])
    if (migration.status === "rejected") throw migration.reason
    if (embedded && !databaseWasConfigured)
      saveBootstrapValue({ name: "DATABASE_URL", value: "embedded" })
    if (sandboxes.status === "rejected") throw sandboxes.reason
    console.error(
      `Bootstrap complete (${((performance.now() - started) / 1000).toFixed(1)}s). Run \`${program.name()} start\` from this directory.`,
    )
  })

program
  .command("version")
  .description("print the version")
  .action(() => console.log(VERSION_OUTPUT))

program
  .command("migrate")
  .description("apply pending database migrations, committing each separately")
  .option("--dry-run", "list pending migrations without applying them")
  .action(async (options: { dryRun?: boolean }) => {
    await preparePlatformDatabase()
    await migratePlatformDatabase(options.dryRun ?? false)
  })

program
  .command("upgrade")
  .description("replace this binary with the latest release or the given one")
  .argument("[version]", "release tag such as v0.13.4 (default: the latest release)")
  .option("-y, --yes", "replace the binary without asking for confirmation")
  .action(async (requested: string | undefined, options: { yes?: boolean }) => {
    const binaryPath = process.execPath
    try {
      // Never replace the runtime when invoked from a checkout. https://bun.sh/docs/bundler/executables
      if (!Bun.isStandaloneExecutable) {
        throw new Error(
          "upgrade replaces a compiled binary, so pull and rebuild a checkout instead",
        )
      }
      if (!RELEASE_TARGET) throw new Error(`no release binary for ${BINARY_HOST}`)
      let tag = requested
      if (!tag) {
        const response = await fetch(
          `https://api.github.com/repos/${APP_RELEASES_REPOSITORY}/releases/latest`,
        )
        if (!response.ok) throw new Error(`latest release lookup returned HTTP ${response.status}`)
        tag = ((await response.json()) as { tag_name: string }).tag_name
      }
      const version = tag.replace(/^v/, "")
      if (!/^\d+\.\d+\.\d+$/.test(version)) {
        throw new Error(`${tag} is not a release tag such as v0.13.4`)
      }
      const order = version.localeCompare(packageJson.version, undefined, { numeric: true })
      if (order === 0 || (order < 0 && !requested)) {
        return console.log(`Already at ${packageJson.version}`)
      }
      if (order < 0) {
        throw new Error(
          `downgrading to ${version} is not supported, because migrations stay applied`,
        )
      }
      // Earlier releases publish no SHA256SUMS to check the download against.
      if (version.localeCompare("0.13.4", undefined, { numeric: true }) < 0) {
        throw new Error("upgrade supports v0.13.4 and later releases, which publish SHA256SUMS")
      }
      if (
        !options.yes &&
        !confirm(`Replace ${packageJson.version} with ${version} at ${binaryPath}?`)
      ) {
        throw new Error("upgrade cancelled")
      }
      const asset = `${APP_HANDLE}-platform-${RELEASE_TARGET}`
      const releaseUrl = `https://github.com/${APP_RELEASES_REPOSITORY}/releases/download/v${version}`
      const sums = await fetch(`${releaseUrl}/SHA256SUMS`)
      if (!sums.ok) {
        throw new Error(`downloading v${version} SHA256SUMS returned HTTP ${sums.status}`)
      }
      // `sha256sum` writes `<hash>  <name>`, or `<hash> *<name>` in binary mode.
      const expected = (await sums.text())
        .split("\n")
        .map((line) => line.split(/ [ *]/))
        .find(([, name]) => name === asset)?.[0]
      if (!expected) throw new Error(`v${version} SHA256SUMS lists no ${asset}`)
      const response = await fetch(`${releaseUrl}/${asset}`)
      if (!response.ok) {
        throw new Error(`downloading v${version} ${asset} returned HTTP ${response.status}`)
      }
      const bytes = new Uint8Array(await response.arrayBuffer())
      if (createHash("sha256").update(bytes).digest("hex") !== expected) {
        throw new Error(`v${version} ${asset} does not match its SHA256SUMS entry`)
      }
      const downloadDirectory = mkdtempSync(`${binaryPath}.upgrade-`)
      const downloadPath = join(downloadDirectory, "binary")
      try {
        writeFileSync(downloadPath, bytes, { flag: "wx" })
        chmodSync(downloadPath, 0o755)
        // Windows cannot overwrite a running executable, but it can rename one.
        if (process.platform === "win32") renameSync(binaryPath, `${binaryPath}.old`)
        try {
          renameSync(downloadPath, binaryPath)
        } catch (error) {
          if (process.platform === "win32") renameSync(`${binaryPath}.old`, binaryPath)
          throw error
        }
      } finally {
        rmSync(downloadDirectory, { recursive: true, force: true })
      }
      console.log(`Replaced ${packageJson.version} with ${version}`)
      console.log(`Run \`${program.name()} migrate\`, then restart the service`)
    } catch (error) {
      const code = (error as NodeJS.ErrnoException).code
      if (code === "EACCES" || code === "EPERM") {
        program.error(
          `error: cannot replace ${binaryPath}, rerun with write access to it, such as with sudo`,
        )
      }
      program.error(`error: ${error instanceof Error ? error.message : String(error)}`)
    }
  })

await program.parseAsync(process.argv).catch(async (error: unknown) => {
  await stopEmbeddedPostgres().catch(() => undefined)
  program.error(`error: ${error instanceof Error ? error.message : String(error)}`)
})
