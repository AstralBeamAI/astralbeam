const CLI_HELP_FOOTER = `
Environment:
  DATABASE_URL             PostgreSQL connection URL (required)
  DATABASE_ENCRYPTION_KEY  keyring for encrypted settings (required by start)
  BETTER_AUTH_SECRET       authentication secret (generated by bootstrap)
  SKIP_EMAIL_VERIFICATION  set to true to allow password users without email verification
  NODE_ENV                 set to production for production deployments
  ALLOW_INSECURE           set to true to allow HTTP and non-Secure operator cookies
  PORT                     port the server listens on (default 4510)

Environment files load from the current working directory.
Existing environment variables win.
Start prompts for missing database variables and saves them to ~/.astralbeam/platform.json.
Bootstrap and migrate require DATABASE_URL in the environment.`

const BOOTSTRAP_ENVIRONMENT_FILE = join(homedir(), ".astralbeam", "platform.json")

const BOOTSTRAP_PROMPTS = {
  DATABASE_URL: "PostgreSQL connection URL (DATABASE_URL):",
  DATABASE_ENCRYPTION_KEY:
    "Encryption keyring, 32+ characters per entry (DATABASE_ENCRYPTION_KEY):",
}

// Release asset suffixes keyed by `${process.platform}-${process.arch}`.
const RELEASE_TARGETS: Record<string, string> = {
  "linux-x64": "linux-x86_64",
  "linux-arm64": "linux-arm64",
  "darwin-x64": "macos-x86_64",
  "darwin-arm64": "macos-arm64",
  "win32-x64": "windows-x86_64.exe",
}

const BINARY_HOST = `${process.platform}-${process.arch}`
const RELEASE_TARGET = RELEASE_TARGETS[BINARY_HOST]
const VERSION_OUTPUT = `${APP_HANDLE}-platform ${packageJson.version} (${RELEASE_TARGET ?? BINARY_HOST})`

type BootstrapVariable = keyof typeof BOOTSTRAP_PROMPTS

// Fills unset variables from the saved file, prompts on a terminal for any still missing, and
// reports where each value came from.
function loadBootstrapEnvironment(names: BootstrapVariable[], { promptMissing = true } = {}): void {
  const unset = names.filter((name) => process.env[name] === undefined)
  const saved = (
    unset.length && existsSync(BOOTSTRAP_ENVIRONMENT_FILE)
      ? JSON.parse(readFileSync(BOOTSTRAP_ENVIRONMENT_FILE, "utf8"))
      : {}
  ) as Partial<Record<BootstrapVariable, string>>
  const missing = promptMissing ? unset.filter((name) => !saved[name]) : []
  for (const name of missing) {
    const value = prompt(BOOTSTRAP_PROMPTS[name])?.trim()
    if (value) saved[name] = value
  }
  if (missing.some((name) => saved[name])) {
    mkdirSync(dirname(BOOTSTRAP_ENVIRONMENT_FILE), { recursive: true, mode: 0o700 })
    writeFileSync(BOOTSTRAP_ENVIRONMENT_FILE, `${JSON.stringify(saved, null, 2)}\n`, {
      mode: 0o600,
    })
    console.error(`Saved to ${BOOTSTRAP_ENVIRONMENT_FILE}`)
  }
  for (const name of names) {
    if (process.env[name] !== undefined) {
      console.error(`Using ${name} from the environment`)
    } else if (saved[name]) {
      process.env[name] = saved[name]
      console.error(`Using ${name} from ${BOOTSTRAP_ENVIRONMENT_FILE}`)
    }
  }
}

async function migratePlatformDatabase(dryRun: boolean): Promise<void> {
  const names = await migrateDatabase({ dryRun })
  if (names.length === 0) return console.log("No pending migrations")
  console.log(
    `${dryRun ? "Pending" : "Applied"} ${names.length} migration${names.length === 1 ? "" : "s"}:`,
  )
  for (const name of names) console.log(`  ${name}`)
}

const program = new Command(`${APP_HANDLE}-platform`)
  .description("Run the platform server and its maintenance commands.")
  .version(VERSION_OUTPUT)
  .addHelpText("after", CLI_HELP_FOOTER)

program
  .command("start", { isDefault: true })
  .description("start the server (the default command)")
  .action(async () => {
    loadBootstrapEnvironment(["DATABASE_URL", "DATABASE_ENCRYPTION_KEY"])
    getDatabaseEncryptionKeyring()
    process.env.PORT ||= "4510"
    // Keep server initialization lazy so version and migration commands need no running server.
    let serverUrl = new URL("../.output/server/index.mjs", import.meta.url)
    if (Bun.isStandaloneExecutable) {
      // Nitro's traced packages need real paths for package exports and native libraries.
      // https://bun.sh/docs/bundler/executables#listing-embedded-files
      const directory = mkdtempSync(join(tmpdir(), "astralbeam-platform-"))
      process.once("exit", () => rmSync(directory, { recursive: true, force: true }))
      for (const file of Bun.embeddedFiles) {
        const { name } = file as Blob & { name: string }
        if (name.startsWith("server/") || name.startsWith("public/")) {
          const destination = join(directory, name)
          mkdirSync(dirname(destination), { recursive: true })
          writeFileSync(destination, new Uint8Array(await file.arrayBuffer()))
        }
      }
      serverUrl = pathToFileURL(join(directory, "server/index.mjs"))
    }
    await import(serverUrl.href)
  })

program
  .command("bootstrap")
  .description("initialize missing environment defaults and apply pending migrations")
  .action(async () => {
    getDatabaseUrl()
    loadBootstrapEnvironment(["DATABASE_ENCRYPTION_KEY"], { promptMissing: false })
    if (process.env.DATABASE_ENCRYPTION_KEY !== undefined) getDatabaseEncryptionKeyring()
    const storedKeys = new Set<string>()
    const client = new Client({
      connectionString: getDatabaseUrl(),
      connectionTimeoutMillis: 5_000,
    })
    try {
      await client.connect()
      const { rows } = await client.query<{ present: boolean }>(
        "SELECT to_regclass('config') IS NOT NULL AS present",
      )
      if (rows[0]?.present) {
        const stored = await client.query<{ key: string }>("SELECT key FROM config")
        for (const row of stored.rows) storedKeys.add(row.key.toUpperCase())
      }
    } finally {
      await client.end()
    }
    // Existing deployments must keep their encryption key and secure flag defaults.
    if (storedKeys.size > 0) getDatabaseEncryptionKeyring()
    const testingDefault = storedKeys.size === 0 ? "true" : "false"
    const environmentPath = join(process.cwd(), ".env.local")
    const defaults = {
      DATABASE_ENCRYPTION_KEY: randomBytes(32).toString("base64url"),
      BETTER_AUTH_SECRET: randomBytes(32).toString("base64url"),
      ALLOW_INSECURE: testingDefault,
      SKIP_EMAIL_VERIFICATION: testingDefault,
      TURNSTILE_SITE_KEY: "1x00000000000000000000AA",
      TURNSTILE_SECRET_KEY: "1x0000000000000000000000000000000AA",
    }
    for (const [name, value] of Object.entries(defaults)) {
      if (process.env[name] !== undefined || storedKeys.has(name)) continue
      if (existsSync(environmentPath)) chmodSync(environmentPath, 0o600)
      writeFileSync(environmentPath, `\n${name}=${value}\n`, { flag: "a", mode: 0o600 })
      process.env[name] = value
      console.error(`Saved ${name} to ${environmentPath}`)
    }
    getDatabaseEncryptionKeyring()
    await migratePlatformDatabase(false)
  })

program
  .command("version")
  .description("print the version")
  .action(() => console.log(VERSION_OUTPUT))

program
  .command("migrate")
  .description("apply pending database migrations, committing each separately")
  .option("--dry-run", "list pending migrations without applying them")
  .action((options: { dryRun?: boolean }) => migratePlatformDatabase(options.dryRun ?? false))

program
  .command("upgrade")
  .description("replace this binary with the latest release or the given one")
  .argument("[version]", "release tag such as v0.13.4 (default: the latest release)")
  .option("-y, --yes", "replace the binary without asking for confirmation")
  .action(async (requested: string | undefined, options: { yes?: boolean }) => {
    const binaryPath = process.execPath
    try {
      // Never replace the runtime when invoked from a checkout. https://bun.sh/docs/bundler/executables
      if (!Bun.isStandaloneExecutable) {
        throw new Error(
          "upgrade replaces a compiled binary, so pull and rebuild a checkout instead",
        )
      }
      if (!RELEASE_TARGET) throw new Error(`no release binary for ${BINARY_HOST}`)
      let tag = requested
      if (!tag) {
        const response = await fetch(
          `https://api.github.com/repos/${APP_RELEASES_REPOSITORY}/releases/latest`,
        )
        if (!response.ok) throw new Error(`latest release lookup returned HTTP ${response.status}`)
        tag = ((await response.json()) as { tag_name: string }).tag_name
      }
      const version = tag.replace(/^v/, "")
      if (!/^\d+\.\d+\.\d+$/.test(version)) {
        throw new Error(`${tag} is not a release tag such as v0.13.4`)
      }
      const order = version.localeCompare(packageJson.version, undefined, { numeric: true })
      if (order === 0 || (order < 0 && !requested)) {
        return console.log(`Already at ${packageJson.version}`)
      }
      if (order < 0) {
        throw new Error(
          `downgrading to ${version} is not supported, because migrations stay applied`,
        )
      }
      // Earlier releases publish no SHA256SUMS to check the download against.
      if (version.localeCompare("0.13.4", undefined, { numeric: true }) < 0) {
        throw new Error("upgrade supports v0.13.4 and later releases, which publish SHA256SUMS")
      }
      if (
        !options.yes &&
        !confirm(`Replace ${packageJson.version} with ${version} at ${binaryPath}?`)
      ) {
        throw new Error("upgrade cancelled")
      }
      const asset = `${APP_HANDLE}-platform-${RELEASE_TARGET}`
      const releaseUrl = `https://github.com/${APP_RELEASES_REPOSITORY}/releases/download/v${version}`
      const sums = await fetch(`${releaseUrl}/SHA256SUMS`)
      if (!sums.ok) {
        throw new Error(`downloading v${version} SHA256SUMS returned HTTP ${sums.status}`)
      }
      // `sha256sum` writes `<hash>  <name>`, or `<hash> *<name>` in binary mode.
      const expected = (await sums.text())
        .split("\n")
        .map((line) => line.split(/ [ *]/))
        .find(([, name]) => name === asset)?.[0]
      if (!expected) throw new Error(`v${version} SHA256SUMS lists no ${asset}`)
      const response = await fetch(`${releaseUrl}/${asset}`)
      if (!response.ok) {
        throw new Error(`downloading v${version} ${asset} returned HTTP ${response.status}`)
      }
      const bytes = new Uint8Array(await response.arrayBuffer())
      if (createHash("sha256").update(bytes).digest("hex") !== expected) {
        throw new Error(`v${version} ${asset} does not match its SHA256SUMS entry`)
      }
      const downloadDirectory = mkdtempSync(`${binaryPath}.upgrade-`)
      const downloadPath = join(downloadDirectory, "binary")
      try {
        writeFileSync(downloadPath, bytes, { flag: "wx" })
        chmodSync(downloadPath, 0o755)
        // Windows cannot overwrite a running executable, but it can rename one.
        if (process.platform === "win32") renameSync(binaryPath, `${binaryPath}.old`)
        try {
          renameSync(downloadPath, binaryPath)
        } catch (error) {
          if (process.platform === "win32") renameSync(`${binaryPath}.old`, binaryPath)
          throw error
        }
      } finally {
        rmSync(downloadDirectory, { recursive: true, force: true })
      }
      console.log(`Replaced ${packageJson.version} with ${version}`)
      console.log(`Run \`${program.name()} migrate\`, then restart the service`)
    } catch (error) {
      const code = (error as NodeJS.ErrnoException).code
      if (code === "EACCES" || code === "EPERM") {
        program.error(
          `error: cannot replace ${binaryPath}, rerun with write access to it, such as with sudo`,
        )
      }
      program.error(`error: ${error instanceof Error ? error.message : String(error)}`)
    }
  })

await program.parseAsync(process.argv).catch((error: unknown) => {
  program.error(`error: ${error instanceof Error ? error.message : String(error)}`)
})
